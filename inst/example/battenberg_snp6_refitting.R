# Parameters
PLATFORM_GAMMA <- 0.55
PHASING_GAMMA <- 1
SEGMENTATION_GAMMA <- 10
CLONALITY_DIST_METRIC <- 0
ASCAT_DIST_METRIC <- 1
MIN_PLOIDY <- 1.6
