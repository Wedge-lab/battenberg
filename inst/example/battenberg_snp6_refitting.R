# Change to work directory and load the chromosome information
setwd(RUN_DIR)
chrom_names <- get_chrom_names(IMPUTEINFOFILE, TRUE)

# Infer what the gender is
gender <- infer_gender_birdseed(BIRDSEED_REPORT_FILE)
is_male <- gender == "male"
chrom_names <- get_chrom_names(IMPUTEINFOFILE, is_male)

# Fit a clonal copy number profile
fit_copy_number(
  samplename = TUMOURNAME,
  outputfile_prefix = paste(TUMOURNAME, "_", sep = ""),
  inputfile_baf_segmented = paste(TUMOURNAME, ".BAFsegmented.txt", sep = ""),
  inputfile_baf = paste(TUMOURNAME, "_mutantBAF.tab", sep = ""),
  inputfile_logr = paste(TUMOURNAME, "_mutantLogR.tab", sep = ""),
  dist_choice = CLONALITY_DIST_METRIC,
  ascat_dist_choice = ASCAT_DIST_METRIC,
  min_ploidy = MIN_PLOIDY,
  max_ploidy = MAX_PLOIDY,
  min_rho = MIN_RHO,
  min_goodness = MIN_GOODNESS_OF_FIT,
  uninformative_baf_threshold = BALANCED_THRESHOLD,
  gamma_param = PLATFORM_GAMMA,
  use_preset_rho_psi = TRUE,
  preset_rho = PRESET_RHO,
  preset_psi = PRESET_PSI,
  read_depth = 30,
  nthreads = NTHREADS
)

# Go over all segments, determine which segements are a mixture of two states and fit a second CN state
call_subclones(
  sample_name = TUMOURNAME,
  baf_segmented_file = paste(TUMOURNAME, ".BAFsegmented.txt", sep = ""),
  logr_file = paste(TUMOURNAME, "_mutantLogR.tab", sep = ""),
  rho_psi_file = paste(TUMOURNAME, "_rho_and_psi.txt", sep = ""),
  output_file = paste(TUMOURNAME, "_subclones.txt", sep = ""),
  output_figures_prefix = paste(TUMOURNAME, "_subclones_chr", sep = ""),
  output_gw_figures_prefix = paste(TUMOURNAME, "_BattenbergProfile", sep = ""),
  chr_names = chrom_names,
  gamma = PLATFORM_GAMMA,
  segmentation_gamma = NA,
  siglevel = 0.05,
  maxdist = 0.01,
  noperms = 1000
)
